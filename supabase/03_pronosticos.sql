-- Pronóstico SC — módulo de pronósticos por colaborador (año + trimestre).
-- Ejecutar en Supabase → SQL Editor → New query → Run. Se puede ejecutar más de una vez.
--
-- Reglas:
--   * Administradores (pr_admins): ven y editan todo, dan de alta / eliminan pronósticos,
--     cambian año/trimestre y replican a cualquier persona.
--   * Colaboradores (@bafar.com.mx): ven SOLO sus pronósticos; dentro de ellos agregan,
--     editan y eliminan indicadores, tareas y ponderaciones, capturan el real y
--     replican los suyos a otros trimestres (solo para sí mismos).
-- Requiere public.es_usuario_permitido() (creada en schema.sql).

-- 1. Tablas
create table if not exists public.pr_admins (
  email text primary key check (email = lower(email))
);

create table if not exists public.pr_empleados (
  email        text primary key check (email = lower(email) and email like '%@bafar.com.mx'),
  num_empleado text not null unique check (length(trim(num_empleado)) > 0),
  nombre       text
);

create table if not exists public.pr_pronosticos (
  id         bigint generated by default as identity primary key,
  email      text not null references public.pr_empleados(email) on update cascade,
  anio       smallint not null check (anio between 2000 and 2100),
  trimestre  smallint not null check (trimestre between 1 and 4),
  creado_por text default (auth.jwt() ->> 'email'),
  creado_en  timestamptz not null default now(),
  unique (email, anio, trimestre)
);

create table if not exists public.pr_indicadores (
  id             bigint generated by default as identity primary key,
  pronostico_id  bigint not null references public.pr_pronosticos(id) on delete cascade,
  nombre         text not null,
  medible        text,
  peso           numeric not null default 0 check (peso >= 0),
  orden          smallint not null default 99
);
create index if not exists pr_indicadores_pron_idx on public.pr_indicadores (pronostico_id);

create table if not exists public.pr_tareas (
  id              bigint generated by default as identity primary key,
  indicador_id    bigint not null references public.pr_indicadores(id) on delete cascade,
  nombre          text not null,
  peso            numeric not null default 0 check (peso >= 0),
  meta            numeric not null check (meta > 0),
  unidad          text not null default '%',
  orden           smallint not null default 99,
  real            numeric check (real is null or real >= 0),
  actualizado_por text,
  actualizado_en  timestamptz
);
create index if not exists pr_tareas_ind_idx on public.pr_tareas (indicador_id);

-- 2. Funciones de permiso
create or replace function public.pr_yo() returns text
language sql stable as $$ select lower(auth.jwt() ->> 'email') $$;

create or replace function public.pr_es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select public.es_usuario_permitido() and exists (select 1 from public.pr_admins where email = public.pr_yo());
$$;

create or replace function public.pr_puede_pron(pid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.es_usuario_permitido() and (public.pr_es_admin() or exists
    (select 1 from public.pr_pronosticos where id = pid and email = public.pr_yo()));
$$;

create or replace function public.pr_puede_ind(iid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.pr_puede_pron((select pronostico_id from public.pr_indicadores where id = iid));
$$;

-- 3. Auditoría de la captura del real
create or replace function public.pr_tareas_auditoria() returns trigger
language plpgsql as $$
begin
  -- solo registra quién/cuándo cuando cambia el valor real
  if (tg_op = 'INSERT' and new.real is not null) or (tg_op = 'UPDATE' and new.real is distinct from old.real) then
    new.actualizado_por := coalesce(auth.jwt() ->> 'email', new.actualizado_por);
    new.actualizado_en  := now();
  elsif tg_op = 'INSERT' then
    new.actualizado_por := null; new.actualizado_en := null;
  end if;
  return new;
end $$;
drop trigger if exists pr_tareas_auditoria on public.pr_tareas;
create trigger pr_tareas_auditoria before insert or update on public.pr_tareas
  for each row execute function public.pr_tareas_auditoria();

-- 4. Seguridad por renglón
alter table public.pr_admins      enable row level security;
alter table public.pr_empleados   enable row level security;
alter table public.pr_pronosticos enable row level security;
alter table public.pr_indicadores enable row level security;
alter table public.pr_tareas      enable row level security;

do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies
           where schemaname = 'public' and tablename in ('pr_admins','pr_empleados','pr_pronosticos','pr_indicadores','pr_tareas')
  loop execute format('drop policy %I on public.%I', r.policyname, r.tablename); end loop;
end $$;

create policy "admin: ver mi permiso" on public.pr_admins for select to authenticated using (email = public.pr_yo());

create policy "empleados: ver"      on public.pr_empleados for select to authenticated using (public.pr_es_admin() or email = public.pr_yo());
create policy "empleados: alta"     on public.pr_empleados for insert to authenticated with check (public.pr_es_admin());
create policy "empleados: editar"   on public.pr_empleados for update to authenticated using (public.pr_es_admin()) with check (public.pr_es_admin());
create policy "empleados: eliminar" on public.pr_empleados for delete to authenticated using (public.pr_es_admin());

create policy "pronosticos: ver"      on public.pr_pronosticos for select to authenticated using (public.pr_puede_pron(id));
create policy "pronosticos: alta"     on public.pr_pronosticos for insert to authenticated with check (public.pr_es_admin());
create policy "pronosticos: editar"   on public.pr_pronosticos for update to authenticated using (public.pr_es_admin()) with check (public.pr_es_admin());
create policy "pronosticos: eliminar" on public.pr_pronosticos for delete to authenticated using (public.pr_es_admin());

create policy "indicadores: ver"      on public.pr_indicadores for select to authenticated using (public.pr_puede_pron(pronostico_id));
create policy "indicadores: alta"     on public.pr_indicadores for insert to authenticated with check (public.pr_puede_pron(pronostico_id));
create policy "indicadores: editar"   on public.pr_indicadores for update to authenticated using (public.pr_puede_pron(pronostico_id)) with check (public.pr_puede_pron(pronostico_id));
create policy "indicadores: eliminar" on public.pr_indicadores for delete to authenticated using (public.pr_puede_pron(pronostico_id));

create policy "tareas: ver"      on public.pr_tareas for select to authenticated using (public.pr_puede_ind(indicador_id));
create policy "tareas: alta"     on public.pr_tareas for insert to authenticated with check (public.pr_puede_ind(indicador_id));
create policy "tareas: editar"   on public.pr_tareas for update to authenticated using (public.pr_puede_ind(indicador_id)) with check (public.pr_puede_ind(indicador_id));
create policy "tareas: eliminar" on public.pr_tareas for delete to authenticated using (public.pr_puede_ind(indicador_id));

-- 5. Replicar (copia indicadores y tareas a otras personas / trimestres)
create or replace function public.pr_replicar(src bigint, destinos text[], periodos jsonb, copiar_real boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  yo text := public.pr_yo();
  d text; per jsonb; nuevo bigint; ind record; nind bigint;
  creados bigint[] := '{}'; omitidos int := 0;
begin
  if not public.pr_puede_pron(src) then raise exception 'No tienes acceso a ese pronóstico.'; end if;
  if not public.pr_es_admin() and exists (select 1 from unnest(destinos) x where lower(x) <> yo) then
    raise exception 'Solo puedes replicar a tus propios pronósticos.';
  end if;
  foreach d in array destinos loop
    for per in select * from jsonb_array_elements(periodos) loop
      if exists (select 1 from pr_pronosticos where email = lower(d)
                 and anio = (per->>'anio')::smallint and trimestre = (per->>'trimestre')::smallint) then
        omitidos := omitidos + 1; continue;
      end if;
      insert into pr_pronosticos (email, anio, trimestre, creado_por)
        values (lower(d), (per->>'anio')::smallint, (per->>'trimestre')::smallint, yo) returning id into nuevo;
      for ind in select * from pr_indicadores where pronostico_id = src loop
        insert into pr_indicadores (pronostico_id, nombre, medible, peso, orden)
          values (nuevo, ind.nombre, ind.medible, ind.peso, ind.orden) returning id into nind;
        insert into pr_tareas (indicador_id, nombre, peso, meta, unidad, orden, real)
          select nind, nombre, peso, meta, unidad, orden, case when copiar_real then real end
          from pr_tareas where indicador_id = ind.id;
      end loop;
      creados := creados || nuevo;
    end loop;
  end loop;
  return jsonb_build_object('creados', to_jsonb(creados), 'omitidos', omitidos);
end $$;

-- 6. Permisos de tabla (la RLS decide qué renglones)
revoke all on public.pr_admins, public.pr_empleados, public.pr_pronosticos, public.pr_indicadores, public.pr_tareas from anon;
grant select on public.pr_admins to authenticated;
grant select, insert, update, delete on public.pr_empleados, public.pr_pronosticos, public.pr_indicadores, public.pr_tareas to authenticated;
revoke all on function public.pr_replicar(bigint, text[], jsonb, boolean) from public, anon;
grant execute on function public.pr_replicar(bigint, text[], jsonb, boolean) to authenticated;

