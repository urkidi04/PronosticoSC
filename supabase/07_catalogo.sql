-- Pronóstico SC — catálogo de tareas.
-- Ejecutar después de 06_liberacion.sql. Se puede ejecutar más de una vez.
--
--   * Toda tarea que se agrega a un pronóstico queda ligada a una tarea del catálogo
--     (si no existe por nombre, se crea sola). Y desde el catálogo se asigna a uno o varios empleados.
--   * Al asignar o quitar, los pesos de las tareas del indicador se reparten parejo (opcional).
--   * Todos ven el catálogo (para elegir al capturar); solo el administrador lo edita y asigna.

create table if not exists public.pr_catalogo (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  clave      text generated always as (lower(regexp_replace(trim(nombre), '\s+', ' ', 'g'))) stored,
  unidad     text not null default '%',
  meta       numeric not null default 100 check (meta > 0),
  descripcion text,
  creado_por text default (auth.jwt() ->> 'email'),
  creado_en  timestamptz not null default now()
);
create unique index if not exists pr_catalogo_clave_idx on public.pr_catalogo (clave);

alter table public.pr_tareas add column if not exists catalogo_id bigint;
do $$ begin
  alter table public.pr_tareas add constraint pr_tareas_catalogo_fk foreign key (catalogo_id) references public.pr_catalogo(id) on delete set null;
exception when duplicate_object then null; end $$;
create index if not exists pr_tareas_catalogo_idx on public.pr_tareas (catalogo_id);

-- 1. Ligar (o crear) la tarea del catálogo por nombre
create or replace function public.pr_catalogo_de(n text, u text, m numeric) returns bigint
language plpgsql security definer set search_path = public as $$
declare cid bigint; k text := lower(regexp_replace(trim(n), '\s+', ' ', 'g'));
begin
  if coalesce(k,'') = '' then return null; end if;
  select id into cid from pr_catalogo where clave = k;
  if cid is null then
    insert into pr_catalogo (nombre, unidad, meta) values (regexp_replace(trim(n), '\s+', ' ', 'g'), coalesce(u,'%'), case when m > 0 then m else 100 end)
      on conflict (clave) do nothing returning id into cid;
    if cid is null then select id into cid from pr_catalogo where clave = k; end if;
  end if;
  return cid;
end $$;

create or replace function public.pr_tareas_catalogo() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if current_setting('pr.fusion', true) = '1' then return new; end if;   -- fusión del catálogo en curso
  if tg_op = 'INSERT' or new.nombre is distinct from old.nombre or new.catalogo_id is null then
    -- si la tarea viene del catálogo (catalogo_id puesto y mismo nombre), se respeta
    if not (new.catalogo_id is not null and exists (select 1 from public.pr_catalogo c where c.id = new.catalogo_id
            and c.clave = lower(regexp_replace(trim(new.nombre), '\s+', ' ', 'g')))) then
      new.catalogo_id := public.pr_catalogo_de(new.nombre, new.unidad, new.meta);
    end if;
  end if;
  return new;
end $$;
drop trigger if exists pr_tareas_catalogo on public.pr_tareas;
create trigger pr_tareas_catalogo before insert or update of nombre, catalogo_id on public.pr_tareas
  for each row execute function public.pr_tareas_catalogo();

-- Ligar las tareas que ya existen
update public.pr_tareas set catalogo_id = public.pr_catalogo_de(nombre, unidad, meta) where catalogo_id is null;

-- 2. Seguridad
alter table public.pr_catalogo enable row level security;
drop policy if exists "catalogo: ver"      on public.pr_catalogo;
drop policy if exists "catalogo: alta"     on public.pr_catalogo;
drop policy if exists "catalogo: editar"   on public.pr_catalogo;
drop policy if exists "catalogo: eliminar" on public.pr_catalogo;
create policy "catalogo: ver"      on public.pr_catalogo for select to authenticated using (public.es_usuario_permitido());
create policy "catalogo: alta"     on public.pr_catalogo for insert to authenticated with check (public.pr_es_admin());
create policy "catalogo: editar"   on public.pr_catalogo for update to authenticated using (public.pr_es_admin()) with check (public.pr_es_admin());
create policy "catalogo: eliminar" on public.pr_catalogo for delete to authenticated using (public.pr_es_admin());
revoke all on public.pr_catalogo from anon;
grant select, insert, update, delete on public.pr_catalogo to authenticated;
grant update (catalogo_id) on public.pr_tareas to authenticated;

-- Renombrar en el catálogo actualiza el nombre en los pronósticos en borrador (los liberados conservan su nombre)
create or replace function public.pr_catalogo_renombra() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.nombre is distinct from old.nombre then
    update pr_tareas t set nombre = new.nombre
      from pr_indicadores i join pr_pronosticos p on p.id = i.pronostico_id
      where t.indicador_id = i.id and t.catalogo_id = new.id and p.estado = 'borrador';
  end if;
  return new;
end $$;
drop trigger if exists pr_catalogo_renombra on public.pr_catalogo;
create trigger pr_catalogo_renombra after update of nombre on public.pr_catalogo
  for each row execute function public.pr_catalogo_renombra();

-- 3. Repartir pesos parejo en un indicador
create or replace function public.pr_repartir(iid bigint) returns void
language sql security definer set search_path = public as $$
  update pr_tareas set peso = 100.0 / nullif((select count(*) from pr_tareas where indicador_id = iid), 0) where indicador_id = iid;
$$;

-- 4. Asignar una tarea del catálogo a varios empleados (administrador)
create or replace function public.pr_asignar_tarea(cat bigint, destinos text[], anio smallint, trimestre smallint,
  indicador text, meta numeric default null, unidad text default null, repartir boolean default true, incluir_liberados boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  c pr_catalogo; d text; p pr_pronosticos; iid bigint; res jsonb := '[]'::jsonb; ord smallint;
begin
  if not public.pr_es_admin() then raise exception 'Solo el administrador puede asignar tareas del catálogo.'; end if;
  select * into c from pr_catalogo where id = cat; if c.id is null then raise exception 'La tarea no existe en el catálogo.'; end if;
  if coalesce(trim(indicador),'') = '' then raise exception 'Indica en qué indicador se agrega.'; end if;
  foreach d in array destinos loop
    select * into p from pr_pronosticos x where x.email = lower(d) and x.anio = pr_asignar_tarea.anio and x.trimestre = pr_asignar_tarea.trimestre;
    if p.id is null then res := res || jsonb_build_object('email', d, 'resultado', 'sin_pronostico'); continue; end if;
    if p.estado <> 'borrador' and not incluir_liberados then res := res || jsonb_build_object('email', d, 'resultado', 'liberado'); continue; end if;
    if exists (select 1 from pr_tareas t join pr_indicadores i on i.id = t.indicador_id where i.pronostico_id = p.id and t.catalogo_id = cat) then
      res := res || jsonb_build_object('email', d, 'resultado', 'ya_la_tiene'); continue;
    end if;
    select id into iid from pr_indicadores where pronostico_id = p.id and lower(trim(nombre)) = lower(trim(indicador)) order by orden, id limit 1;
    if iid is null then
      select coalesce(max(orden),0)+1 into ord from pr_indicadores where pronostico_id = p.id;
      insert into pr_indicadores (pronostico_id, nombre, peso, orden) values (p.id, trim(indicador), 0, ord) returning id into iid;
    end if;
    select coalesce(max(orden),0)+1 into ord from pr_tareas where indicador_id = iid;
    insert into pr_tareas (indicador_id, nombre, peso, meta, unidad, orden, catalogo_id)
      values (iid, c.nombre, 0, coalesce(meta, c.meta), coalesce(unidad, c.unidad), ord, c.id);
    if repartir then perform pr_repartir(iid); end if;
    res := res || jsonb_build_object('email', d, 'resultado', 'asignada');
  end loop;
  return res;
end $$;

-- 5. Quitar una tarea asignada (administrador) y repartir el resto
create or replace function public.pr_quitar_tarea(tid bigint, repartir boolean default true)
returns void language plpgsql security definer set search_path = public as $$
declare iid bigint;
begin
  if not public.pr_es_admin() then raise exception 'Solo el administrador puede quitar tareas desde el catálogo.'; end if;
  select indicador_id into iid from pr_tareas where id = tid;
  delete from pr_tareas where id = tid;
  if repartir and iid is not null then perform pr_repartir(iid); end if;
end $$;

-- 6. Fusionar dos tareas del catálogo (origen → destino) (administrador)
--    Las tareas ligadas al origen pasan al destino; en pronósticos en borrador toman el nombre del destino.
create or replace function public.pr_fusionar_catalogo(origen bigint, destino bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare d pr_catalogo; n int; ambas int;
begin
  if not public.pr_es_admin() then raise exception 'Solo el administrador puede fusionar tareas del catálogo.'; end if;
  if origen = destino then raise exception 'Elige dos tareas distintas.'; end if;
  select * into d from pr_catalogo where id = destino;
  if d.id is null or not exists (select 1 from pr_catalogo where id = origen) then raise exception 'La tarea no existe en el catálogo.'; end if;
  select count(distinct i.pronostico_id) into ambas from pr_tareas t join pr_indicadores i on i.id = t.indicador_id
    where t.catalogo_id = origen and i.pronostico_id in (select i2.pronostico_id from pr_tareas t2 join pr_indicadores i2 on i2.id = t2.indicador_id where t2.catalogo_id = destino);
  perform set_config('pr.fusion', '1', true);
  update pr_tareas t set catalogo_id = destino,
    nombre = case when (select p.estado from pr_indicadores i join pr_pronosticos p on p.id = i.pronostico_id where i.id = t.indicador_id) = 'borrador' then d.nombre else t.nombre end
    where t.catalogo_id = origen;
  get diagnostics n = row_count;
  perform set_config('pr.fusion', '0', true);
  delete from pr_catalogo where id = origen;
  return jsonb_build_object('tareas', n, 'pronosticos_con_ambas', ambas, 'destino', d.nombre);
end $$;
revoke all on function public.pr_fusionar_catalogo(bigint, bigint) from public, anon;
grant execute on function public.pr_fusionar_catalogo(bigint, bigint) to authenticated;

revoke all on function public.pr_asignar_tarea(bigint, text[], smallint, smallint, text, numeric, text, boolean, boolean) from public, anon;
revoke all on function public.pr_quitar_tarea(bigint, boolean) from public, anon;
revoke all on function public.pr_repartir(bigint) from public, anon, authenticated;
revoke all on function public.pr_catalogo_de(text, text, numeric) from public, anon, authenticated;
grant execute on function public.pr_asignar_tarea(bigint, text[], smallint, smallint, text, numeric, text, boolean, boolean) to authenticated;
grant execute on function public.pr_quitar_tarea(bigint, boolean) to authenticated;

